def pick(key: str, **kw: Any) -> str:
    """从 ``key`` 对应的池子里随机取一句；可选的 ``kw`` 用于格式化占位符。

    Args:
        key: 场景名（见 :data:`POOLS`）。不存在时回退到通用句。
        **kw: 喂给 ``str.format`` 的变量，例如 ``title="晴天"``。

    Returns:
        str: 一句可以直接塞进气泡的中文台词。格式化失败时返回未格式化的原文。
    """
    pool = POOLS.get(key) or _FALLBACK
    try:
        text = random.choice(pool)
    except (IndexError, TypeError):
        return _FALLBACK[0]
    if not kw:
        return text
    try:
        return text.format(**kw)
    except Exception:
        # 占位符缺失 / 文本里混了裸花括号：原文更安全，至少不会崩
        return text
